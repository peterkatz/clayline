"""What a filled interior actually lays down, measured on the emitted G-code.

Every accept criterion for the Interior feature is a claim about clay: where
the fill sits relative to the wall it welds to, whether a rib has anything
under it, how often the nozzle lifts.  None of those can be settled by reading
the builder — they are settled by running the route Pete runs (mesh -> slice
-> modulate -> finalize -> gcode) and measuring the file that comes out.  So
this module drives the same HTTP endpoints as
:mod:`tests.test_pineapple_crown_sliver` and reuses that module's own G-code
parser rather than writing a second one that would be free to disagree with it.

The two forms are the fixtures the feature was shaped around: ``teapot-lid``,
a shallow closed dome that is filled edge to edge on every layer, for the solid
interior; and ``tall-tumbler``, 39 layers of a gently bellied cylinder, for the
sparse one.  Both live in ``tests/fixtures/mesh`` and are generated by
``scripts/generate_mesh_fixtures.py``, so these measurements run everywhere —
nothing here reaches for a scan outside the repository.

``reproducible=True`` is on for every emission so that the only thing standing
between two runs of the same job is geometry, not a clock.
"""

