def test_infill_tumbler_lifts_once_a_layer_and_no_more() -> None:
    """Item 3's accept criterion, met on the emitted file.

    The criterion is "travel count per layer <= island count + segment splits
    the raster proofs force".  This form has one island a layer and no forced
    split, so the whole budget is one lift — the hop up from the layer below —
    and the ribs, their turnarounds, the weld and the wall spend nothing.

    An earlier round spent two, having found that a straight bead from the last
    rib to the wall seam crossed the open lattice (887 mm of it over a cone
    print) and chosen a travel instead.  The straight bead was the mistake, not
    the weld: the route that stays over clay rides the region's inset boundary
    and steps half a bead out onto the wall.  Clay does not stop and start —
    there is no retraction on a paste extruder — so the budget is the thing
    that holds and the route is what has to be right.
    """

    _sliced, _modulated, gcode = _sparse_tumbler()
    moves = _body_print_moves(gcode)
    travels = _travel_groups(gcode)
    layers = _printed_layers(moves)

    for layer in layers:
        islands = _island_count(moves, layer)
        forced_splits = len(_fill_runs(moves, gcode, layer)) - islands
        assert islands == 1
        assert forced_splits == 0
        assert travels[layer] == islands + forced_splits
        assert travels[layer] == 1

    # Said the other way round, because this is the sentence Pete measured the
    # feature by: over the whole body the nozzle leaves the clay once per
    # printed layer and not once more.  The first layer's own travel is the
    # approach from the park position, which every route pays.
    assert sum(travels.values()) == len(layers)


def test_the_rib_its_weld_and_its_wall_are_one_deposition_run() -> None:
    """One island's layer is a single unbroken run, and the weld is inside it.

    A run is what lies between two lifts.  If the ribs and the wall are in the
    same run there is no travel between them, which is the whole claim; and the
    weld is findable in the file — it carries the fill's own note with ``weld``
    on the end — so its length can be measured rather than inferred.
    """

    _sliced, _modulated, gcode = _sparse_tumbler()
    moves = _body_print_moves(gcode)

    for layer in _printed_layers(moves):
        runs = _runs(moves, gcode, layer)
        assert len(runs) == 1, layer
        # Fill, then weld, then wall, in that order and with nothing between.
        # The prime ramp at the head of a run and the end-early taper at its
        # tail carry notes of their own and are the emitter's business, not
        # this measurement's.
        order = ("fill", "weld", "wall")
        kinds = [
            "weld" if _is_weld(move) else "wall" if _is_wall(move) else "fill"
            for move in runs[0]
            if _is_weld(move) or _is_wall(move) or _is_fill(move)
        ]
        assert set(kinds) == set(order), layer
        assert kinds == sorted(kinds, key=order.index), layer

    # The weld itself: from the last rib point through the weld moves onto the
    # wall seam, half a bead of step plus whatever ride the boundary needed.
    welds = _weld_paths(moves, gcode)
    assert len(welds) == len(_printed_layers(moves))
    for layer, path in welds.items():
        assert BEAD_WIDTH / 2.0 <= path.length <= BEAD_WIDTH, layer


def test_infill_tumbler_is_lighter_than_the_same_form_solid() -> None:
    _sliced, _modulated, sparse = _sparse_tumbler()
    _solid_sliced, _solid_modulated, solid = _emit(TUMBLER, interior="solid")

    sparse_mass = _header_number(sparse, "wet_weight_g")
    solid_mass = _header_number(solid, "wet_weight_g")
    hollow_mass = _header_number(_emit(TUMBLER, interior="hollow")[2], "wet_weight_g")

    # Ribs exist to carry a form without the drying mass of solid clay.  The
    # report has to show that, or the control is decorative.
    #
    # 237.274555 g before the ribs welded to their walls, and the 8.31 g between
    # the two numbers is worth naming because only a tenth of it is new bead.
    # The welds themselves add 88.4 mm of path.  The other 195 mm is path this
    # form was already driving under a PRIME RAMP: every deposition run starts
    # with 5 mm of ramping extrusion that lays less than a bead, and halving the
    # run count from 78 to 39 halves what that costs.  So most of the extra clay
    # is not clay that was added — it is clay that was being missed at every
    # restart, which is the ooze-and-blob the weld exists to stop.
    assert sparse_mass == pytest.approx(245.589324, abs=1e-4)
    assert solid_mass == pytest.approx(598.963563, abs=1e-4)
    assert hollow_mass == pytest.approx(108.481843, abs=1e-4)
    assert sparse_mass < 0.5 * solid_mass
    assert hollow_mass < sparse_mass < solid_mass
    assert "; CLAYLINE_BODY_END" in sparse


